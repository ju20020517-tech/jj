  function fill(t, vars = {}) {
    return t.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? vars[k] : ''));
  }
  // 상황 대사 (말투 적용)
  function say(v, key, vars, raw) {
    const arr = L[key];
    const t = fill(Array.isArray(arr) ? pick(arr) : (arr || key), vars);
    return raw ? t : sty(v, t);
  }
  function greet(v, stage, vars) {
    const g = GREET[stage] || GREET.ACQUAINTANCE;
    const formal = styleOf(v) === 'FORMAL' || stage === 'ACQUAINTANCE';
    const t = fill(pick(formal ? g.formal : g.casual), vars);
    return stage === 'ACQUAINTANCE' ? t : sty(v, t);
  }
  function topic(v) {
    if (styleOf(v) === 'FORMAL') return TOPIC_FORMAL[v.keys.L1] || '좋은 하루입니다.';
    const pool = [...(TOPIC[v.keys.L1] || []), ...(TOPIC[v.keys.L4] || [])];
    return sty(v, pick(pool) + '.');
  }

